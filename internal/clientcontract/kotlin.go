// Kotlin is the Android contract: the types, names and order Methods writes for
// Swift, as kotlinx.serialization classes. Kotlin can't add a nested type from a
// second file, so the event types Swift keeps in HostEvents.swift are here too.
func Kotlin(specs []rpc.Spec) string {
	g, events, _ := methodsGen(specs)
	k := kotlinGen{names: g.names}
	members := map[string]*strings.Builder{}
	member := func(family string) *strings.Builder {
		if members[family] == nil {
			members[family] = &strings.Builder{}
		}
		return members[family]
	}

	for _, s := range g.methods {
		split := strings.LastIndexByte(s.Name, '.')
		namespace := swiftFamily(s.Name[:split])
		base := namespace + "." + pascal(s.Name[split+1:])
		fmt.Fprintf(member(namespace), "    val %s = HostAPIMethod(%q, serializer<HostAPI.%sParams>(), serializer<%s>())\n",
			kotlinIdent(swiftIdent(s.Name[split+1:])), s.Name, base, k.typeRef(s.Result))
	}
	for _, name := range g.order {
		if _, owned := events.bodies[name]; owned {
			continue
		}
		family, _, _ := strings.Cut(name, ".")
		member(family).WriteString("\n" + k.class(g, name, ""))
	}

	exported := map[string]string{}
	for _, ev := range hostemit.Catalog() {
		if name, ok := EventExports[ev.Method()]; ok {
			exported[name] = ev.Method()
		}
	}
	eventNames := make([]string, 0, len(events.bodies))
	for name := range events.bodies {
		eventNames = append(eventNames, name)
	}
	sort.Strings(eventNames)
	for _, name := range eventNames {
		family, _, _ := strings.Cut(name, ".")
		member(family).WriteString("\n" + k.class(events, name, exported[name]))
	}
	for _, family := range []string{"terminals", "forward", "chats"} {
		namespace := swiftFamily(family)
		member(namespace).WriteString("\n" + kotlinEventFamily(family, namespace))
	}

	families := make([]string, 0, len(members))
	for family := range members {
		families = append(families, family)
	}
	sort.Strings(families)
	var b strings.Builder
	b.WriteString("// Generated by `go test ./internal/rpc/conformance -update` in apps/host. Do not edit.\n\n")
	b.WriteString(kotlinPrelude)
	b.WriteString("\nobject HostAPI {\n")
	for i, family := range families {
		if i > 0 {
			b.WriteString("\n")
		}
		fmt.Fprintf(&b, "  object %s {\n%s  }\n", family, members[family].String())
	}
	b.WriteString(kotlinToolList(specs))
	b.WriteString("}\n")
	return b.String()
}

type kotlinGen struct {
	names map[reflect.Type]string // Go struct → its Swift and Kotlin name
}

// class is one generated type; method is its wire name when it is an exported event.
func (k kotlinGen) class(g *swiftGen, name, method string) string {
	t := g.types[name]
	simple := name[strings.LastIndexByte(name, '.')+1:]
	if kotlinTypeNames[simple] {
		panic("Kotlin type name shadows a built-in: " + name)
	}
	var b strings.Builder
	b.WriteString("    @Serializable\n")
	fields := wiredoc.Fields(t)
	props := g.props[name]
	if len(fields) == 0 {
		fmt.Fprintf(&b, "    class %s", simple)
	} else {
		fmt.Fprintf(&b, "    data class %s(\n", simple)
		for i, f := range fields {
			p := props[i]
			ty := k.typeRef(f.Type)
			if ty == "ByteArray" {
				b.WriteString("      @Serializable(with = Base64Serializer::class)\n")
			} else if strings.Contains(ty, "ByteArray") {
				panic("unsupported Kotlin byte field: " + name + "." + f.Name)
			}
			if p.optional {
				ty = strings.TrimSuffix(ty, "?") + "? = null"
			}
			fmt.Fprintf(&b, "      @SerialName(%q) val %s: %s,\n", p.json, kotlinIdent(p.swift), ty)
		}
		b.WriteString("    )")
	}
	if method != "" {
		fmt.Fprintf(&b, " {\n      companion object : HostEvent<%s> {\n        override val method = %q\n        override fun decode(json: Json, data: ByteArray): %s = json.decodeFromString(serializer(), data.decodeToString())\n      }\n    }", simple, method, simple)
	}
	b.WriteString("\n")
	return b.String()
}

// typeRef is the Kotlin spelling of t, after the checks Swift's typeRef ran.
func (k kotlinGen) typeRef(t reflect.Type) string {
	switch {
	case t.Kind() == reflect.Pointer:
		return strings.TrimSuffix(k.typeRef(t.Elem()), "?") + "?"
	case t == wiredoc.RawMessage:
		return "JsonElement"
	case t == timeT:
		return "String"
	}
	switch t.Kind() {
	case reflect.String:
		return "String"
	case reflect.Bool:
		return "Boolean"
	// Go's int is 64-bit, as Swift's Int is.
	case reflect.Int, reflect.Int64:
		return "Long"
	case reflect.Int8, reflect.Int16, reflect.Int32:
		return "Int"
	case reflect.Float32, reflect.Float64:
		return "Double"
	case reflect.Slice, reflect.Array:
		if t.Kind() == reflect.Slice && t.Elem().Kind() == reflect.Uint8 {
			return "ByteArray"
		}
		return "List<" + k.typeRef(t.Elem()) + ">"
	case reflect.Map:
		return "Map<String, " + k.typeRef(t.Elem()) + ">"
	case reflect.Interface:
		return "JsonElement"
	case reflect.Struct:
		name, ok := k.names[t]
		if !ok {
			panic("Kotlin type without a Swift name: " + t.String())
		}
		return "HostAPI." + name
	}
	panic("unsupported Kotlin mapping: " + t.String())
}

func kotlinEventFamily(family, namespace string) string {
	var cases, decodes strings.Builder
	for _, ev := range hostemit.Catalog() {
		name := EventExports[ev.Method()]
		if !strings.HasPrefix(ev.Method(), family+".") || name == "" {
			continue
		}
		_, bare, _ := strings.Cut(ev.Method(), ".")
		ident := kotlinIdent(swiftIdent(bare))
		fmt.Fprintf(&cases, "      data class %s(val value: HostAPI.%s) : Event()\n", ident, name)
		fmt.Fprintf(&decodes, "          HostAPI.%s.method -> %s(HostAPI.%s.decode(json, data))\n", name, ident, name)
	}
	return fmt.Sprintf(`    /** The family's events in wire order, for a consumer that needs several kinds. */
    sealed class Event {
%s
      companion object : HostEventFamily<Event> {
        override val family = %q
        override fun decode(method: String, json: Json, data: ByteArray): Event? = when (method) {
%s          else -> null
        }
      }
    }
`, cases.String(), family, decodes.String())
}

func kotlinToolList(specs []rpc.Spec) string {
	var b strings.Builder
	b.WriteString("\n  /** Methods agents and cards may call: a read feeds a card's Data and reloads on its liveOn events. */\n")
	b.WriteString("  val tools: Map<String, HostAPITool> = mapOf(\n")
	for _, s := range specs {
		if s.Tool == "" {
			continue
		}
		events := make([]string, len(s.LiveOn))
		for i, ev := range s.LiveOn {
			events[i] = fmt.Sprintf("%q", ev)
		}
		fmt.Fprintf(&b, "    %q to HostAPITool(readOnly = %t, liveOn = listOf(%s)),\n", s.Name, s.Effect == rpc.Reads, strings.Join(events, ", "))
	}
	b.WriteString("  )\n")
	return b.String()
}

// kotlinIdent is a Swift property name in Kotlin: the same word, re-escaped.
func kotlinIdent(swift string) string {
	name := strings.Trim(swift, "`")
	if kotlinKeywords[name] {
		return "`" + name + "`"
	}
	return name
}

var kotlinKeywords = map[string]bool{"as": true, "break": true, "class": true, "continue": true, "do": true,
	"else": true, "false": true, "for": true, "fun": true, "if": true, "in": true, "interface": true, "is": true,
	"null": true, "object": true, "package": true, "return": true, "super": true, "this": true, "throw": true,
	"true": true, "try": true, "typealias": true, "typeof": true, "val": true, "var": true, "when": true, "while": true}

// Names a nested class must not take: they would shadow what the generated code spells.
var kotlinTypeNames = map[string]bool{"String": true, "Boolean": true, "Int": true, "Long": true, "Double": true,
	"ByteArray": true, "List": true, "Map": true, "JsonElement": true, "Json": true, "Any": true, "Unit": true,
	"Event": true, "HostEvent": true, "HostAPIMethod": true, "HostAPITool": true}

const kotlinPrelude = `package app.repogo.hostcontract

import java.util.Base64
import kotlinx.serialization.KSerializer
import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable
import kotlinx.serialization.descriptors.PrimitiveKind
import kotlinx.serialization.descriptors.PrimitiveSerialDescriptor
import kotlinx.serialization.encoding.Decoder
import kotlinx.serialization.encoding.Encoder
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.serializer

/** A host method: its wire name and how its params and result cross the wire. */
class HostAPIMethod<Params, Result>(val name: String, val params: KSerializer<Params>, val result: KSerializer<Result>)

/** An event the app decodes, by its full wire name. */
interface HostEvent<T> {
  val method: String
  fun decode(json: Json, data: ByteArray): T
}

/** A family's ordered events, decoded by their full wire names. */
interface HostEventFamily<T> {
  val family: String
  fun decode(method: String, json: Json, data: ByteArray): T?
}

/** A method agents and cards may call: a read feeds a card's Data and reloads on its liveOn events. */
class HostAPITool(val readOnly: Boolean, val liveOn: List<String>)

/** Bytes as Go's encoding/json sends them: standard base64. */
object Base64Serializer : KSerializer<ByteArray> {
  override val descriptor = PrimitiveSerialDescriptor("Base64", PrimitiveKind.STRING)
  override fun serialize(encoder: Encoder, value: ByteArray) = encoder.encodeString(Base64.getEncoder().encodeToString(value))
  override fun deserialize(decoder: Decoder): ByteArray = Base64.getDecoder().decode(decoder.decodeString())
}
`
