// TypeScript is the desktop contract: the types, names and order Methods writes
// for Swift, as interfaces keyed by the wire's own fields, the methods and events
// as values a typed call reads, and each type's fields as data for the golden test.
func TypeScript(specs []rpc.Spec) string {
	g, events, _ := methodsGen(specs, func(string) bool { return true })
	ts := tsGen{names: g.names}
	members := map[string]*strings.Builder{}
	member := func(family string) *strings.Builder {
		if members[family] == nil {
			members[family] = &strings.Builder{}
		}
		return members[family]
	}

	var shapes []string
	for _, name := range g.order {
		if _, owned := events.bodies[name]; owned {
			continue
		}
		family, _, _ := strings.Cut(name, ".")
		member(family).WriteString("\n" + ts.iface(g, name))
		shapes = append(shapes, ts.shape(g, name))
	}
	eventNames := make([]string, 0, len(events.bodies))
	for name := range events.bodies {
		eventNames = append(eventNames, name)
	}
	sort.Strings(eventNames)
	for _, name := range eventNames {
		family, _, _ := strings.Cut(name, ".")
		member(family).WriteString("\n" + ts.iface(events, name))
		shapes = append(shapes, ts.shape(events, name))
	}

	families := make([]string, 0, len(members))
	for family := range members {
		families = append(families, family)
	}
	sort.Strings(families)

	var b strings.Builder
	b.WriteString("// Generated by `go test ./internal/rpc/conformance -update` in apps/host. Do not edit.\n\n")
	b.WriteString(tsPrelude)
	for _, family := range families {
		fmt.Fprintf(&b, "\nexport namespace %s {%s}\n", family, members[family].String())
	}

	b.WriteString("\n/** Every method the desktop may call, by wire name, typed by its params and result. */\nexport const methods = {\n")
	for _, s := range g.methods {
		split := strings.LastIndexByte(s.Name, '.')
		base := swiftFamily(s.Name[:split]) + "." + pascal(s.Name[split+1:])
		result := ts.typeRef(s.Result)
		fmt.Fprintf(&b, "  %q: method<%sParams, %s>(%q, %q, %q),\n", s.Name, base, result, s.Name, base+"Params", ts.shapeName(s.Result))
	}
	b.WriteString("} as const;\n")

	b.WriteString("\n/** Every event the desktop decodes, by wire name. */\nexport const events = {\n")
	for _, ev := range hostemit.Catalog() {
		if name, ok := EventExports[ev.Method()]; ok {
			fmt.Fprintf(&b, "  %q: event<%s>(%q, %q),\n", ev.Method(), name, ev.Method(), name)
		}
	}
	b.WriteString("} as const;\n")

	b.WriteString("\n/** Methods agents and cards may call: a read feeds a card's Data and reloads on its liveOn events. */\nexport const tools: Record<string, HostTool> = {\n")
	for _, s := range specs {
		if s.Tool == "" {
			continue
		}
		events := make([]string, len(s.LiveOn))
		for i, ev := range s.LiveOn {
			events[i] = fmt.Sprintf("%q", ev)
		}
		fmt.Fprintf(&b, "  %q: { readOnly: %t, liveOn: [%s] },\n", s.Name, s.Effect == rpc.Reads, strings.Join(events, ", "))
	}
	b.WriteString("};\n")

	b.WriteString("\n/** Each type's fields as data (wire key, type, flags), for the test that decodes the goldens. */\nexport const shapes: Record<string, readonly HostField[]> = {\n")
	for _, shape := range shapes {
		b.WriteString(shape)
	}
	b.WriteString("};\n")
	return b.String()
}

type tsGen struct {
	names map[reflect.Type]string // Go struct → its Swift and TypeScript name
}

// iface is one generated type, its properties the wire's own keys.
func (ts tsGen) iface(g *swiftGen, name string) string {
	t := g.types[name]
	simple := name[strings.LastIndexByte(name, '.')+1:]
	var b strings.Builder
	fields := wiredoc.Fields(t)
	if len(fields) == 0 {
		fmt.Fprintf(&b, "  export interface %s {}\n", simple)
		return b.String()
	}
	fmt.Fprintf(&b, "  export interface %s {\n", simple)
	for i, f := range fields {
		p := g.props[name][i]
		ty := ts.typeRef(f.Type)
		if f.Nullable || f.Type.Kind() == reflect.Pointer {
			ty += " | null"
		}
		key := f.Name
		if !tsIdentifier.MatchString(key) {
			key = fmt.Sprintf("%q", key)
		}
		if p.optional {
			key += "?"
		}
		fmt.Fprintf(&b, "    %s: %s;\n", key, ty)
	}
	b.WriteString("  }\n")
	return b.String()
}

// shape is the same type as data: `?` marks a field that may be absent,
// `n` one that may be null.
func (ts tsGen) shape(g *swiftGen, name string) string {
	t := g.types[name]
	var b strings.Builder
	fmt.Fprintf(&b, "  %q: [", name)
	for i, f := range wiredoc.Fields(t) {
		p := g.props[name][i]
		flags := ""
		if p.optional {
			flags += "?"
		}
		if f.Nullable || f.Type.Kind() == reflect.Pointer {
			flags += "n"
		}
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(&b, "[%q, %q, %q]", f.Name, ts.typeRef(f.Type), flags)
	}
	b.WriteString("],\n")
	return b.String()
}

var tsIdentifier = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)

// typeRef is the TypeScript spelling of t, after the checks Swift's typeRef
// ran. A pointer is its element; the field adds null.
func (ts tsGen) typeRef(t reflect.Type) string {
	switch {
	case t.Kind() == reflect.Pointer:
		return ts.typeRef(t.Elem())
	case t == wiredoc.RawMessage:
		return "JSONValue"
	case t == timeT:
		return "string"
	}
	switch t.Kind() {
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64, reflect.Float32, reflect.Float64:
		return "number"
	case reflect.Slice, reflect.Array:
		if t.Kind() == reflect.Slice && t.Elem().Kind() == reflect.Uint8 {
			// encoding/json writes bytes as a base64 string.
			return "string"
		}
		return ts.typeRef(t.Elem()) + "[]"
	case reflect.Map:
		return "Record<string, " + ts.typeRef(t.Elem()) + ">"
	case reflect.Interface:
		return "JSONValue"
	case reflect.Struct:
		name, ok := ts.names[t]
		if !ok {
			panic("TypeScript type without a Swift name: " + t.String())
		}
		return name
	}
	panic("unsupported TypeScript mapping: " + t.String())
}

// shapeName is the shapes key for a method's result; a result that is no
// generated type has none.
func (ts tsGen) shapeName(t reflect.Type) string {
	for t.Kind() == reflect.Pointer {
		t = t.Elem()
	}
	if t.Kind() == reflect.Struct && t != timeT {
		if name, ok := ts.names[t]; ok {
			return name
		}
	}
	return ""
}

const tsPrelude = `/** Any JSON the host sends untyped. */
export type JSONValue = null | boolean | number | string | JSONValue[] | { [key: string]: JSONValue };

/** A host method: its wire name, and the shapes of what it takes and answers. */
export interface HostMethod<Params, Result> {
  readonly name: string;
  readonly params: string;
  readonly result: string;
  /** Never set: carries the types for a call to read. */
  readonly types?: { params: Params; result: Result };
}

/** An event the app decodes, by its full wire name. */
export interface HostEvent<Params> {
  readonly method: string;
  readonly shape: string;
  readonly types?: Params;
}

/** A method agents and cards may call: a read feeds a card's Data and reloads on its liveOn events. */
export interface HostTool {
  readonly readOnly: boolean;
  readonly liveOn: readonly string[];
}

/** One field of a generated type: its wire key, its type as written here, and ` + "`?`" + ` absent or ` + "`n`" + ` null. */
export type HostField = readonly [key: string, type: string, flags: string];

function method<Params, Result>(name: string, params: string, result: string): HostMethod<Params, Result> {
  return { name, params, result };
}

function event<Params>(method: string, shape: string): HostEvent<Params> {
  return { method, shape };
}
`
